<h1>Pasang TESYS di HP</h1>
<p class="pnd-lead">
    TESYS dapat ditambahkan ke Home Screen sehingga terbuka seperti aplikasi
    (tanpa address bar). Aplikasi tetap membutuhkan koneksi internet; data
    keuangan tidak disimpan di perangkat.
</p>

<h2>Android (Chrome)</h2>
<ol class="pnd-steps">
    <li>Buka alamat TESYS di <strong>Chrome</strong> dan login.</li>
    <li>Ketuk menu <strong>&#8942;</strong> di kanan atas, pilih <strong>Instal aplikasi</strong> atau <strong>Tambahkan ke layar utama</strong>.</li>
    <li>Konfirmasi. Ikon TESYS muncul di Home Screen.</li>
</ol>

<h2>iPhone (Safari)</h2>
<ol class="pnd-steps">
    <li>Buka alamat TESYS di <strong>Safari</strong> (bukan browser lain).</li>
    <li>Ketuk tombol <strong>Bagikan</strong>, lalu <strong>Tambah ke Layar Utama</strong>.</li>
    <li>Ketuk <strong>Tambah</strong>. Buka TESYS dari ikon di Home Screen.</li>
</ol>
<p>Catatan: di iPhone, aplikasi Home Screen memakai sesi terpisah dari Safari, jadi Anda perlu login sekali lagi.</p>

<h2>Membuka dan memperbarui</h2>
<ul>
    <li>Buka TESYS dari ikon Home Screen. Bila sesi habis, Anda diarahkan ke halaman login.</li>
    <li>Pembaruan aplikasi otomatis mengikuti server; tidak perlu memasang ulang. Jika tampilan terasa usang, tutup aplikasi sepenuhnya lalu buka kembali.</li>
    <li>Bila koneksi putus, muncul halaman "Tidak ada koneksi" &mdash; ketuk <strong>Coba lagi</strong> setelah jaringan pulih.</li>
</ul>
