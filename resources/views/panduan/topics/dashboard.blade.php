<h1>Dashboard</h1>
<p class="pnd-lead">
    Dashboard adalah halaman pertama setelah login. Fungsinya memberi gambaran
    singkat: pembaruan aplikasi terbaru dan jejak aktivitas tim.
</p>

<h2>Siapa yang mengakses</h2>
<div class="pnd-roles">
    <span class="pnd-role">Semua pengguna login</span>
</div>
<p>Dashboard tidak digerbang hak akses menu — selalu tampil untuk setiap user.</p>

<h2>Bagian halaman</h2>
<h3>1. What's New (highlight)</h3>
<p>
    Menampilkan rilis versi Tesys paling baru: judul rilis, tanggal, ringkasan,
    serta daftar perubahan yang dikelompokkan sebagai <strong>Baru</strong>,
    <strong>Perubahan</strong>, atau <strong>Perbaikan</strong>. Nomor versi yang
    sedang berjalan tampil sebagai badge <code>v x.y.z</code>.
</p>
<p>
    Klik <strong>Riwayat versi</strong> untuk membuka daftar lengkap seluruh rilis
    sejak aplikasi digunakan.
</p>

<h3>2. Last Activity</h3>
<p>
    Aliran aktivitas terbaru yang relevan dengan Anda — perubahan status milestone,
    pengisian actual finish, mention, dan tonggak proyek. Klik salah satu baris
    untuk melompat ke halaman terkait.
</p>

<h2>Kolom bantuan</h2>
<p>
    Tombol <i class="fas fa-question-circle"></i> <strong>Panduan</strong> di kiri
    atas (samping tombol buka/tutup sidebar) membuka panduan ini kapan saja.
</p>

<div class="pnd-callout tip">
    <i class="fas fa-lightbulb"></i>
    <span>Versi aplikasi juga ditampilkan kecil di bawah logo pada sidebar,
    sehingga Anda selalu tahu build yang sedang dipakai saat melapor kendala.</span>
</div>
