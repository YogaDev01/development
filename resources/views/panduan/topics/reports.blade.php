<h1>Reports</h1>
<p class="pnd-lead">
    Halaman Reports mengumpulkan laporan keuangan yang bisa difilter per periode
    dan diekspor untuk kebutuhan internal maupun customer.
</p>

<h2>Siapa yang mengakses</h2>
<div class="pnd-roles">
    <span class="pnd-role">Superadmin</span>
    <span class="pnd-role">Finance / Finance Manager</span>
    <span class="pnd-role">Approver / CEO</span>
</div>

<h2>Jenis laporan</h2>
<ul>
    <li><strong>Budget vs Realisasi</strong> — penyerapan anggaran per cost center / project.</li>
    <li><strong>Cost Request</strong> — rekap pengajuan biaya beserta statusnya.</li>
    <li><strong>Collection / Aging Invoice</strong> — posisi tagihan customer per umur.</li>
    <li><strong>Cash Flow</strong> — arus kas masuk/keluar per periode.</li>
</ul>

<h2>Cara pakai</h2>
<ol class="pnd-steps">
    <li>Pilih jenis laporan.</li>
    <li>Tentukan <strong>periode</strong> dan filter tambahan (cost center, project, customer).</li>
    <li>Klik <strong>Terapkan</strong> untuk menampilkan.</li>
    <li>Gunakan <strong>Export Excel / PDF</strong> untuk mengunduh.</li>
</ol>

<div class="pnd-callout tip">
    <i class="fas fa-lightbulb"></i>
    <span>Untuk integrasi lanjutan (mis. Excel Power Query), tersedia Public API
    ber-token untuk data Budget Request — hubungi tim Finance/IT untuk token.</span>
</div>
