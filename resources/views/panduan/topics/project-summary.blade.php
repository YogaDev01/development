<h1>Summary (Service Delivery)</h1>
<p class="pnd-lead">
    Service Delivery Summary memberi gambaran progres seluruh proyek yang sedang
    berjalan dalam satu layar — untuk kebutuhan monitoring manajemen proyek.
</p>

<h2>Siapa yang mengakses</h2>
<div class="pnd-roles">
    <span class="pnd-role">Superadmin</span>
    <span class="pnd-role">Head</span>
    <span class="pnd-role">Project Manager</span>
    <span class="pnd-role">Approver / CEO</span>
</div>

<h2>Isi halaman</h2>
<ul>
    <li><strong>Kartu ringkas</strong> — jumlah proyek aktif, on-track vs terlambat, dan progres rata-rata.</li>
    <li><strong>Daftar proyek</strong> dengan persentase progres (plan vs actual) dan PM Internal.</li>
    <li><strong>Indikator keterlambatan</strong> — proyek dengan actual di bawah plan disorot.</li>
</ul>

<h2>Cara membaca</h2>
<ol class="pnd-steps">
    <li>Pilih periode / cluster bila tersedia.</li>
    <li>Urutkan berdasarkan <strong>deviasi</strong> untuk melihat proyek paling tertinggal lebih dulu.</li>
    <li>Klik satu proyek untuk masuk ke <a href="{{ route('panduan.show', 'project-monitoring') }}">Project Monitoring</a> detailnya.</li>
</ol>

<div class="pnd-callout">
    <i class="fas fa-info-circle"></i>
    <span>Angka progres berasal dari pengisian milestone di Project Monitoring —
    Summary tidak bisa diedit langsung.</span>
</div>
