<h1>Todo List</h1>
<p class="pnd-lead">
    Todo List mengumpulkan seluruh permintaan yang menunggu tindakan Anda —
    approval Cost Request, verifikasi, revisi, dan sejenisnya — dalam satu daftar
    dengan informasi umur (aging) tiap item.
</p>

<h2>Siapa yang mengakses</h2>
<div class="pnd-roles">
    <span class="pnd-role">Semua role yang punya task</span>
    <span class="pnd-role">Head</span>
    <span class="pnd-role">Finance</span>
    <span class="pnd-role">Finance Manager</span>
    <span class="pnd-role">Approver / CEO</span>
</div>

<h2>Dua tempat melihat task</h2>
<ul>
    <li><strong>Lonceng "Todo" di navbar</strong> — ringkasan cepat jumlah task dan yang paling lama menunggu. Klik judul untuk membuka halaman penuh.</li>
    <li><strong>Halaman Todo List</strong> — daftar lengkap dengan filter dan aging per item.</li>
</ul>

<h2>Langkah penggunaan</h2>
<ol class="pnd-steps">
    <li>Buka menu <strong>Finance &rarr; Todo List</strong>.</li>
    <li>Perhatikan kolom <strong>umur</strong> — item yang menua perlu diprioritaskan.</li>
    <li>Klik satu baris untuk membuka dokumen aslinya (mis. Cost Request).</li>
    <li>Lakukan tindakan yang diminta (approve / reject / revisi) pada halaman dokumen tersebut.</li>
    <li>Item hilang dari daftar setelah statusnya berpindah dari tangan Anda.</li>
</ol>

<div class="pnd-callout">
    <i class="fas fa-info-circle"></i>
    <span>Aging pada Todo List dihitung <strong>sejak dokumen masuk ke status saat ini</strong>,
    bukan sejak pertama kali dibuat — supaya beban antrean tiap tahap terlihat jujur.</span>
</div>
